/**
 * Sends an email notification using Resend REST API if configured,
 * otherwise logs to notification center with fallback.
 */
export async function sendNotification(
  payload: NotificationPayload
): Promise<{ success: boolean; notificationId: string }> {
  const notifId = `notif-${Date.now()}`;
  const record: NotificationPayload = {
    ...payload,
    id: notifId,
    createdAt: new Date().toISOString(),
    read: false,
  };

  inMemoryNotifications.unshift(record);

  // If Resend API key is present in environment, dispatch HTTP email
  if (process.env.RESEND_API_KEY) {
    try {
      const res = await fetch('https://api.resend.com/emails', {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          Authorization: `Bearer ${process.env.RESEND_API_KEY}`,
        },
        body: JSON.stringify({
          from: 'AutoApplyPilot <pilot@autoapplypilot.dev>',
          to: payload.to,
          subject: payload.title,
          html: renderEmailHtml(record),
        }),
      });

      if (!res.ok) {
        console.warn('Resend API dispatch failed:', await res.text());
      }
    } catch (err) {
      console.warn('Email dispatch network error:', err);
    }
  }

  return { success: true, notificationId: notifId };
}
