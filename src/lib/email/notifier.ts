export type NotificationType =
  | 'HIGH_MATCH'
  | 'APPLICATION_SUBMITTED'
  | 'INTERVIEW_INVITE'
  | 'REJECTION'
  | 'DAILY_DIGEST';

export interface NotificationPayload {
  id?: string;
  to: string;
  type: NotificationType;
  title: string;
  body: string;
  jobDetails?: {
    title: string;
    company: string;
    score?: number;
    url?: string;
  };
  createdAt?: string;
  read?: boolean;
}

